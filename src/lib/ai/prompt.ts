export const FOOD_RECOGNITION_PROMPT = `Ты диетолог и эксперт по компьютерному зрению. Внимательно проанализируй приложенное ФОТО еды.

Оцени именно то, что видно на этом конкретном фото:
- название блюда на русском языке
- размер порции на фото (тарелка, контейнер, рука для масштаба)
- калории и БЖУ всей видимой порции (не усреднённые значения из справочника)

Ответь ТОЛЬКО валидным JSON без markdown и комментариев:
{
  "dishName": "название блюда",
  "calories": 0,
  "protein": 0,
  "fat": 0,
  "carbs": 0,
  "portionGrams": 0,
  "confidence": 0.0,
  "alternatives": [
    { "dishName": "вариант", "calories": 0 }
  ]
}

Правила:
- Все числа должны отражать именно эту порцию на фото
- Маленькая порция — меньше калорий, большая — больше
- Не подставляй одинаковые значения для разных блюд
- confidence: от 0 до 1
- alternatives: 1-3 варианта, если блюдо неочевидно; иначе пустой массив
- если на фото не еда: dishName "Не удалось распознать еду", calories 0, confidence 0.1, alternatives []`;

export function buildFoodLookupPrompt(dishName: string): string {
  return `Ты диетолог. Пользователь указал название блюда: "${dishName}".

Оцени типичную одну порцию этого блюда (домашняя/кафе, Россия) и верни ТОЛЬКО JSON без markdown:
{
  "dishName": "уточнённое название на русском",
  "calories": 0,
  "protein": 0,
  "fat": 0,
  "carbs": 0,
  "portionGrams": 0,
  "confidence": 0.0,
  "alternatives": []
}

Правила:
- dishName: исправь опечатки, сделай название понятным (на русском)
- calories, protein, fat, carbs: для одной стандартной порции
- portionGrams: примерный вес порции в граммах
- confidence: от 0 до 1, насколько уверены в оценке
- alternatives: оставь пустым массивом`;
}
