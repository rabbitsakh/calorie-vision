  "brand": "",
  "barcode": "",
  "calories": 0,
  "protein": 0,
  "fat": 0,
  "carbs": 0,
  "fiber": 0,
  "sugar": 0,
  "saturatedFat": 0,
  "portionGrams": 0,
  "per100g": { "calories": 0, "protein": 0, "fat": 0, "carbs": 0, "fiber": 0, "sugar": 0, "saturatedFat": 0 },
  "confidence": 0.0,
  "alternatives": []
