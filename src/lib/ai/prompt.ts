export const FOOD_RECOGNITION_PROMPT = `Ты диетолог и эксперт по компьютерному зрению. Внимательно проанализируй приложенное ФОТО.

Сначала определи тип фото (photoKind):
- "meal" — готовая еда / блюдо на тарелке, в контейнере, домашняя готовка
- "package" — заводская упаковка продукта (пачка, банка, бутылка, обёртка), без крупной таблицы КБЖУ
- "label" — этикетка / таблица пищевой ценности (КБЖУ, «на 100 г», состав)
- "barcode" — крупно виден штрихкод, либо штрихкод хорошо читается на упаковке

Затем извлеки данные. Ответь ТОЛЬКО валидным JSON без markdown и комментариев:
{
  "photoKind": "meal",
  "dishName": "название на русском",
  "brand": "",
  "barcode": "",
  "calories": 0,
  "protein": 0,
  "fat": 0,
  "carbs": 0,
  "portionGrams": 0,
  "per100g": {
    "calories": 0,
    "protein": 0,
    "fat": 0,
    "carbs": 0
  },
  "confidence": 0.0,
  "alternatives": [
    { "dishName": "вариант", "calories": 0 }
  ]
}

Правила:
- barcode: только цифры штрихкода (EAN-8/EAN-13/UPC), если виден. Иначе пустая строка
- brand: бренд с упаковки, если виден
- dishName: для упаковки — название продукта (не «упаковка»); для этикетки — продукт с этикетки; для блюда — блюдо
- portionGrams: вес видимой порции или нетто упаковки в граммах, если указан
- per100g: заполни, если на этикетке есть КБЖУ на 100 г. Иначе все нули
- calories/protein/fat/carbs:
  - meal: оценка всей порции на фото
  - label: значения с этикетки для указанного веса (если есть «на 100 г» и нетто — пересчитай на нетто)
  - package/barcode: оценка по упаковке, если цифр нет — разумная оценка порции
- confidence: от 0 до 1
- alternatives: 1-3 варианта, если продукт неочевиден; иначе []
- если это не еда и не продукт питания: dishName "Не удалось распознать еду", calories 0, confidence 0.1, photoKind "meal"`;

export function buildFoodLookupPrompt(dishName: string): string {
  return `Ты диетолог. Пользователь указал название блюда: "${dishName}".

Оцени типичную одну порцию этого блюда (домашняя/кафе, Россия) и верни ТОЛЬКО JSON без markdown:
{
  "photoKind": "meal",
  "dishName": "уточнённое название на русском",
  "brand": "",
  "barcode": "",
  "calories": 0,
  "protein": 0,
  "fat": 0,
  "carbs": 0,
  "portionGrams": 0,
  "per100g": { "calories": 0, "protein": 0, "fat": 0, "carbs": 0 },
  "confidence": 0.0,
  "alternatives": []
}

Правила:
- dishName: исправь опечатки, сделай название понятным (на русском)
- calories, protein, fat, carbs: для одной стандартной порции
- portionGrams: примерный вес порции в граммах
- confidence: от 0 до 1
- alternatives: оставь пустым массивом`;
}
